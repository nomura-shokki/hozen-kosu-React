# 種別       : パッケージ初期化ファイル（中身は空）
# 概要       : このフォルダ（kosu/）を Python の「パッケージ」として認識させるための空ファイル。
#              パッケージとは、複数の .py ファイルをフォルダ単位でひとまとめにしたもの。
#              このファイルがあることで、他のファイルから
#              「from kosu.models import member」のようにフォルダ名を使って import（読み込み）できる。
#
# 補足       : kosu/ は工数管理システム本体の Django アプリ（機能のまとまり）。
#              settings.py の INSTALLED_APPS に 'kosu' として登録されている。
#              コードを書く必要はないため、空のまま残しておくこと（削除しない）。
# 関連ファイル: apps.py（KosuConfig: アプリの設定）, hozen_another/settings.py（INSTALLED_APPS）
