# ============================================================
# ファイル名 : clear_session_middleware.py
# 種別       : ミドルウェア（Django）
# 概要       : 処理中のHTTPリクエストを「スレッドローカル」に一時保存し、
#              リクエストを直接受け取れない場所（signals.py など）からも取り出せるようにする。
#              ミドルウェアとは、すべてのリクエスト/レスポンスの前後に共通処理を差し込む仕組みのこと。
#
# 主なクラス / 関数:
#   - CurrentRequestMiddleware : リクエスト処理中だけ、そのリクエストをスレッドローカルに保存する
#   - get_current_request      : 保存中のリクエストを取り出す（なければ None）
#
# 使われ方   : signals.py が操作履歴（History）を記録するとき、get_current_request() で
#              リクエストを取り出し、セッションの login_No（ログイン者の従業員番号）を記録する。
#              ※ファイル名は「clear_session」だが、セッションを消去する処理は行っていない。
# 関連ファイル: signals.py, hozen_another/settings.py（MIDDLEWARE に登録）
# ============================================================

# ============================================================
# インポート
# ============================================================
import threading



# スレッドローカルオブジェクト作成
#   スレッドローカル: スレッド（同時に動く処理の単位）ごとに別々の値を持てる入れ物。
#   サーバーは複数のリクエストを別スレッドで同時に処理するため、
#   普通のグローバル変数だと他人のリクエストと混ざってしまう。これを防ぐために使う。
_request_local = threading.local()
# ------------------------------------------------------------
# CurrentRequestMiddleware: 現在のリクエストを保存するミドルウェア
#   各リクエストの処理中、現在のHTTPリクエストオブジェクトをスレッドローカルに保存し、
#   処理が終わったら消す。settings.py の MIDDLEWARE の最後に登録されている。
# ------------------------------------------------------------
class CurrentRequestMiddleware:
  # ミドルウェアを初期化する（Django の起動時に1回だけ呼ばれる）。
  #
  # 引数:
  #   get_response: 次のミドルウェア（最後ならビュー）を呼び出してレスポンスを得る関数
  # 戻り値:
  #   なし
  def __init__(self, get_response):
    # 次のミドルウェア（またはビュー）を呼び出す関数を保持しておく
    self.get_response = get_response


  # 1件のリクエストを処理する（リクエストのたびに呼ばれる）。
  #
  # ビューの処理が動いている間だけ、リクエストをスレッドローカルに置いておく。
  #
  # 引数:
  #   request: HTTPリクエスト
  # 戻り値:
  #   HttpResponse: 次のミドルウェア（またはビュー）が返したレスポンスをそのまま返す
  def __call__(self, request):
    # 現在のリクエストオブジェクトをスレッドローカルに保存
    _request_local.request = request
    # 次のミドルウェア（またはビュー）を呼び出してレスポンスを受け取る
    #   この間にデータが保存・削除されると signals.py が get_current_request() を呼ぶ
    response = self.get_response(request)

    # スレッドローカル内のリクエストオブジェクトを削除する
    #   （メモリリーク防止と、同じスレッドで次に処理する別リクエストに古い情報が残らないようにするため）
    _request_local.request = None
    return response



# 現在のスレッドで処理中のHTTPリクエストを取り出す。
#
# リクエストの外（asynchronous_views.py が別スレッドで動かすバックアップ・復元処理や、
# manage.py のコマンドなど）から呼ばれた場合は、保存されたリクエストが無いため None を返す。
#
# 引数:
#   なし
# 戻り値:
#   HttpRequest: 処理中のリクエスト。存在しない場合は None
def get_current_request():
  # スレッドローカルから 'request' 属性を取り出す（一度も保存されていないスレッドでは None）
  return getattr(_request_local, 'request', None)
